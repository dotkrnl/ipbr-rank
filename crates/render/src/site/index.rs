pub fn render_index(scoreboard: &Scoreboard) -> String {
    let mut body = String::new();

    let radar_scales = top10_axis_scales(scoreboard);

    body.push_str(&render_hero(scoreboard, radar_scales));

    body.push_str(SCORING_PANEL);

    body.push_str(
        r#"<p class="provisional-note"><span aria-hidden="true">*</span> provisional — direct-evidence requirements not met</p>"#,
    );

    body.push_str(&render_leaderboard(scoreboard, radar_scales));

    write!(
        body,
        r#"<footer>generated by {generator} · {generated_at} · <a href="about.html">about</a> · <a href="scoreboard.toml">api</a></footer>"#,
        generator = html_escape(&scoreboard.generator),
        generated_at = html_escape(&scoreboard.generated_at),
    )
    .unwrap();

    layout("ipbr · live llm coding scoreboard", &body)
}

fn render_hero(scoreboard: &Scoreboard, radar_scales: RadarScales) -> String {
    let top3: Vec<&ipbr_core::ModelRecord> =
        dense_ranked_models(scoreboard.models.iter().collect(), composite)
            .into_iter()
            .take(3)
            .map(|(_, model)| model)
            .collect();

    let radar_slices: Vec<RadarSlice> = top3
        .iter()
        .enumerate()
        .map(|(idx, model)| RadarSlice {
            idea: model.scores.i_raw,
            plan: model.scores.p_raw,
            build: model.scores.b_raw,
            review: model.scores.r,
            class: rank_class(idx),
            label: Some(model.display_name.as_str()),
            provisional: ipbr_core::balanced_is_provisional(model),
        })
        .rev() // draw rank-3 first so rank-1 sits on top
        .collect();
    let radar_svg = render_radar(&radar_slices, RadarVariant::Hero, radar_scales);

    let mut legend = String::from(r#"<ul class="hero-radar-legend">"#);
    for (idx, model) in top3.iter().enumerate() {
        write!(
            legend,
            r#"<li><span class="legend-dot {cls}" aria-hidden="true"></span><span class="legend-name">{name}</span></li>"#,
            cls = rank_class(idx),
            name = html_escape(&model.display_name),
        )
        .unwrap();
    }
    legend.push_str("</ul>");

    let leaders = render_leaders(scoreboard);

    format!(
        r#"<section class="hero" id="hero"><div class="hero-head"><p class="hero-tagline"><span class="beat beat-lead">Models drift.</span> <span class="beat">Evidence accumulates.</span> <span class="beat beat-final">Ranks update.</span></p><p class="hero-status"><span class="hero-stat"><span class="live-dot" aria-hidden="true"></span><span class="live-label">live</span></span><span class="hero-stat">refreshed <time datetime="{generated_at}" data-local-time>{generated_at}</time></span><span class="hero-stat">{sources} sources</span><span class="hero-stat">{models} models</span></p></div><div class="hero-body"><div class="hero-radar-wrap">{radar_svg}{legend}</div><div class="hero-leaders">{leaders}</div></div></section>"#,
        generated_at = html_escape(&scoreboard.generated_at),
        sources = scoreboard.source_summary.len(),
        models = scoreboard.models.len(),
    )
}

fn render_leaders(scoreboard: &Scoreboard) -> String {
    let mut html =
        String::from(r#"<h3 class="leaders-title">ranked leaders</h3><div class="leaders-grid">"#);
    for spec in role_specs() {
        let ranked = dense_ranked_models(scoreboard.models.iter().collect(), spec.from_record);
        write!(
            html,
            r#"<div class="role {role_id}"><div class="role-head">[ {label} ]</div><ol class="role-list">"#,
            role_id = spec.id,
            label = spec.label,
        )
        .unwrap();
        for (pos, model) in ranked.iter().take(3) {
            let row_class = if *pos == 1 { "row top" } else { "row" };
            let score = (spec.from_record)(model);
            let prev = scoreboard
                .prev_scores
                .as_ref()
                .and_then(|map| map.get(&model.canonical_id))
                .map(spec.from_scores);
            let delta = render_delta(score, prev);
            let score = render_leader_score(score, role_is_provisional(model, spec.evidence_key));
            write!(
                html,
                r#"<li class="{row_class}"><span class="pos">{pos}</span><span class="name">{name}</span><span class="score" data-tier="{tier}">{score}</span>{delta}</li>"#,
                name = html_escape(&model.display_name),
                tier = score_tier((spec.from_record)(model)),
            )
            .unwrap();
        }
        html.push_str("</ol></div>");
    }
    html.push_str("</div>");
    html
}

fn composite(model: &ipbr_core::ModelRecord) -> f64 {
    let s = &model.scores;
    (s.i_raw + s.p_raw + s.b_raw + s.r) / 4.0
}

const RADAR_REFERENCE_COHORT: usize = 10;

/// Fixes each axis's [min, max] to the spread of the top-10 balanced-score
/// models, so every radar on the page (hero and per-row) shares one
/// reference frame instead of each self-normalizing to its own shape.
fn top10_axis_scales(scoreboard: &Scoreboard) -> RadarScales {
    let top10: Vec<&ipbr_core::ModelRecord> =
        dense_ranked_models(scoreboard.models.iter().collect(), composite)
            .into_iter()
            .take(RADAR_REFERENCE_COHORT)
            .map(|(_, model)| model)
            .collect();

    let axis_range = |get: fn(&ipbr_core::RoleScores) -> f64| -> (f64, f64) {
        let mut min = f64::INFINITY;
        let mut max = f64::NEG_INFINITY;
        for model in &top10 {
            let value = get(&model.scores);
            min = min.min(value);
            max = max.max(value);
        }
        (min, max)
    };

    let (idea_min, idea_max) = axis_range(|s| s.i_raw);
    let (plan_min, plan_max) = axis_range(|s| s.p_raw);
    let (build_min, build_max) = axis_range(|s| s.b_raw);
    let (review_min, review_max) = axis_range(|s| s.r);

    RadarScales {
        idea: RadarScale::from_range(idea_min, idea_max),
        plan: RadarScale::from_range(plan_min, plan_max),
        build: RadarScale::from_range(build_min, build_max),
        review: RadarScale::from_range(review_min, review_max),
    }
}

/// Dense ranks aligned with the one-decimal score display: values that round
/// to the same displayed tenth share a rank, and the next distinct score gets
/// the next integer (1, 1, 2 rather than 1, 2, 3).
fn display_score_key(value: f64) -> String {
    format!("{value:.1}")
}

fn dense_ranked_models(
    mut models: Vec<&ipbr_core::ModelRecord>,
    score: fn(&ipbr_core::ModelRecord) -> f64,
) -> Vec<(usize, &ipbr_core::ModelRecord)> {
    models.sort_by(|a, b| {
        score(b)
            .partial_cmp(&score(a))
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| a.canonical_id.cmp(&b.canonical_id))
    });
    let mut dense_rank = 0;
    let mut previous: Option<String> = None;
    models
        .into_iter()
        .map(|model| {
            let value = score(model);
            let display_key = display_score_key(value);
            if previous.as_ref() != Some(&display_key) {
                dense_rank += 1;
                previous = Some(display_key);
            }
            (dense_rank, model)
        })
        .collect()
}

fn role_is_provisional(model: &ipbr_core::ModelRecord, role: &str) -> bool {
    model
        .evidence
        .roles
        .get(role)
        .is_some_and(|coverage| coverage.provisional)
}

fn rank_class(rank: usize) -> &'static str {
    match rank {
        0 => "rank-1",
        1 => "rank-2",
        _ => "rank-3",
    }
}

fn score_tier(score: f64) -> &'static str {
    if score >= 70.0 {
        "high"
    } else if score >= 50.0 {
        "mid"
    } else {
        "low"
    }
}

struct RoleSpec {
    id: &'static str,
    label: &'static str,
    evidence_key: &'static str,
    from_record: fn(&ipbr_core::ModelRecord) -> f64,
    from_scores: fn(&ipbr_core::RoleScores) -> f64,
}

fn role_specs() -> [RoleSpec; 4] {
    [
        RoleSpec {
            id: "idea",
            label: "idea",
            evidence_key: "I_raw",
            from_record: |m| m.scores.i_raw,
            from_scores: |s| s.i_raw,
        },
        RoleSpec {
            id: "plan",
            label: "plan",
            evidence_key: "P_raw",
            from_record: |m| m.scores.p_raw,
            from_scores: |s| s.p_raw,
        },
        RoleSpec {
            id: "build",
            label: "build",
            evidence_key: "B_raw",
            from_record: |m| m.scores.b_raw,
            from_scores: |s| s.b_raw,
        },
        RoleSpec {
            id: "review",
            label: "review",
            evidence_key: "R",
            from_record: |m| m.scores.r,
            from_scores: |s| s.r,
        },
    ]
}

/// Renders a `▲+1.2` / `▼-0.8` chip when the prior score differs by ≥0.05.
/// Returns an empty string when there is no prior score or the change is
/// below the noise floor.
fn render_delta(current: f64, prev: Option<f64>) -> String {
    let Some(prev) = prev else {
        return String::new();
    };
    let delta = current - prev;
    if delta.abs() < 0.05 {
        return String::new();
    }
    let (arrow, cls, dir) = if delta > 0.0 {
        ("▲", "delta delta-up", "up")
    } else {
        ("▼", "delta delta-down", "down")
    };
    format!(
        r#"<span class="{cls}" aria-hidden="true">{arrow}{delta:+.1}</span><span class="sr-only"> {dir} {abs:.1} since yesterday</span>"#,
        abs = delta.abs(),
    )
}

fn render_leaderboard(scoreboard: &Scoreboard, radar_scales: RadarScales) -> String {
    let mut models: Vec<&ipbr_core::ModelRecord> = scoreboard.models.iter().collect();
    // Default order: build score. Individual role columns remain
    // independently sortable.
    models.sort_by(|left, right| {
        right
            .scores
            .b_raw
            .partial_cmp(&left.scores.b_raw)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| left.canonical_id.cmp(&right.canonical_id))
    });

    let mut vendors: std::collections::BTreeSet<&str> = std::collections::BTreeSet::new();
    for model in &models {
        vendors.insert(model.vendor.as_str());
    }

    let mut html = String::from(
        r##"<section id="leaderboard"><div class="toolbar"><div class="search-box"><svg class="search-icon" viewBox="0 0 16 16" aria-hidden="true" focusable="false"><circle cx="6.75" cy="6.75" r="4.75"></circle><line x1="10.4" y1="10.4" x2="14.5" y2="14.5"></line></svg><input data-filter-input="#leaderboard-table" type="search" placeholder="filter" aria-label="filter leaderboard by model or vendor"></div><div class="vendor-chips" role="group" aria-label="filter leaderboard by vendor">"##,
    );
    html.push_str(
        r#"<button type="button" data-vendor="" class="active" aria-pressed="true" aria-label="show all vendors">all</button>"#,
    );
    for vendor in &vendors {
        html.push_str(&format!(
            r#"<button type="button" data-vendor="{v}" aria-pressed="false" aria-label="show only {v} models">{v}</button>"#,
            v = html_escape(vendor),
        ));
    }
    html.push_str(r#"</div></div><div class="lb-scroll"><table class="leaderboard" id="leaderboard-table"><thead><tr>"#);
    html.push_str(
        r#"<th scope="col" data-sort="model" aria-sort="none"><button type="button" class="sort" aria-label="sort by model descending">model</button></th>"#,
    );
    html.push_str(
        r#"<th scope="col" data-sort="vendor" aria-sort="none"><button type="button" class="sort" aria-label="sort by vendor descending">vendor</button></th>"#,
    );

    // Score columns — build is the default sort.
    for (label, key) in [("idea", "i"), ("plan", "p"), ("build", "b")] {
        let (active_attr, aria_sort) = if key == "b" {
            (r#" data-sort-active="desc""#, "descending")
        } else {
            ("", "none")
        };
        html.push_str(&format!(
            r#"<th scope="col" class="num" data-sort="{key}" aria-sort="{aria_sort}"{active_attr}><button type="button" class="sort" aria-label="sort by {label} score descending">{label}</button></th>"#
        ));
    }
    html.push_str(
        r#"<th scope="col" class="num" data-sort="r" aria-sort="none"><button type="button" class="sort" aria-label="sort by review score descending">review</button></th>"#,
    );
    html.push_str(r#"<th scope="col" aria-label="details"></th></tr></thead><tbody>"#);

    for model in &models {
        html.push_str(&render_row(scoreboard, model, radar_scales));
    }

    html.push_str(r#"</tbody></table></div></section>"#);
    html
}

fn render_row(
    scoreboard: &Scoreboard,
    model: &ipbr_core::ModelRecord,
    radar_scales: RadarScales,
) -> String {
    let mut html = String::new();
    let s = &model.scores;
    let id = html_escape(&model.canonical_id);
    let vendor = html_escape(model.vendor.as_str());
    let name = html_escape(&model.display_name);
    let prev = scoreboard
        .prev_scores
        .as_ref()
        .and_then(|map| map.get(&model.canonical_id));

    write!(
        html,
        r#"<tr class="row" id="{id}" data-vendor="{vendor}" data-sort-model="{name_lc}" data-sort-vendor="{vendor}" data-sort-i="{i:.4}" data-sort-p="{p:.4}" data-sort-b="{b:.4}" data-sort-r="{r:.4}"><td class="model-name">{name}</td><td>{vendor}</td>"#,
        name_lc = name.to_lowercase(),
        i = s.i_raw,
        p = s.p_raw,
        b = s.b_raw,
        r = s.r,
    )
    .unwrap();

    type ScoreAccessor = fn(&ipbr_core::RoleScores) -> f64;
    let columns: [(f64, ScoreAccessor, &str); 4] = [
        (s.i_raw, |x| x.i_raw, "I_raw"),
        (s.p_raw, |x| x.p_raw, "P_raw"),
        (s.b_raw, |x| x.b_raw, "B_raw"),
        (s.r, |x| x.r, "R"),
    ];
    for (raw, accessor, role) in columns {
        let provisional = role_is_provisional(model, role);
        let prev_score = prev.map(accessor);
        let delta = render_delta(raw, prev_score);
        write!(
            html,
            r#"<td class="num" data-tier="{tier}" data-status="{status}">{score}{delta}</td>"#,
            tier = score_tier(raw),
            status = if provisional { "provisional" } else { "ranked" },
            score = render_score_value(raw, provisional),
        )
        .unwrap();
    }
    let details_id = format!("{id}-details");
    write!(
        html,
        r#"<td class="expand-toggle"><button type="button" aria-expanded="false" aria-controls="{details_id}" aria-label="show details for {name}" data-label-open="hide details for {name}" data-label-closed="show details for {name}">▸</button></td></tr>"#
    )
    .unwrap();

    let mini_radar = render_radar(
        &[RadarSlice {
            idea: s.i_raw,
            plan: s.p_raw,
            build: s.b_raw,
            review: s.r,
            class: "solo",
            label: Some(model.display_name.as_str()),
            provisional: ipbr_core::balanced_is_provisional(model),
        }],
        RadarVariant::Mini,
        radar_scales,
    );

    write!(
        html,
        r#"<tr class="expand" id="{details_id}" data-row="{id}"><td colspan="7"><div class="expand-inner"><div class="exp-radar">{mini_radar}</div><div class="exp-tables"><section class="exp-block"><h4>role evidence</h4>{evidence}</section><section class="exp-block"><h4>group breakdown</h4>{groups}</section><section class="exp-block"><h4>metrics · raw → normalized</h4>{metrics}</section><section class="exp-block exp-meta"><span class="exp-meta-label">sources</span> {sources}<span class="exp-meta-label">missing ranked inputs</span> {missing}</section></div></div></td></tr>"#,
        evidence = render_role_evidence(model),
        groups = render_group_table(scoreboard, model),
        metrics = render_metric_table(scoreboard, model),
        sources = render_source_pills(scoreboard, model),
        missing = render_missing_pills(model),
    )
    .unwrap();

    html
}

fn render_score_value(value: f64, provisional: bool) -> String {
    if provisional {
        format!(
            r#"<span class="cell-score provisional-score"><em>{value:.1}</em><span class="status-marker" title="Provisional: direct-evidence requirements not met" aria-label="provisional">*</span></span>"#
        )
    } else {
        format!(r#"<span class="cell-score">{value:.1}</span>"#)
    }
}

fn render_leader_score(value: f64, provisional: bool) -> String {
    if provisional {
        format!(
            r#"<span class="provisional-score"><em>{value:.1}</em><span class="status-marker" title="Provisional: direct-evidence requirements not met" aria-label="provisional">*</span></span>"#
        )
    } else {
        format!("{value:.1}")
    }
}

fn rank_for(
    scoreboard: &Scoreboard,
    canonical_id: &str,
    lookup: impl Fn(&ipbr_core::ModelRecord) -> Option<f64>,
) -> Option<(usize, usize)> {
    let mut scored: Vec<(f64, &str)> = scoreboard
        .models
        .iter()
        .filter_map(|m| lookup(m).map(|v| (v, m.canonical_id.as_str())))
        .collect();
    if scored.is_empty() {
        return None;
    }
    scored.sort_by(|a, b| {
        b.0.partial_cmp(&a.0)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then_with(|| a.1.cmp(b.1))
    });
    let mut dense_rank = 0;
    let mut previous: Option<String> = None;
    for (score, id) in &scored {
        let display_key = display_score_key(*score);
        if previous.as_ref() != Some(&display_key) {
            dense_rank += 1;
            previous = Some(display_key);
        }
        if *id == canonical_id {
            return Some((dense_rank, scored.len()));
        }
    }
    None
}

fn rank_bar_width(rank: Option<(usize, usize)>) -> f64 {
    match rank {
        Some((p, total)) if total > 0 => ((total - p + 1) as f64) / (total as f64) * 100.0,
        _ => 0.0,
    }
}

fn rank_text(rank: Option<(usize, usize)>) -> (String, &'static str) {
    match rank {
        Some((1, total)) => (format!("1 / {total}"), "exp-rank top"),
        Some((p, total)) => (format!("{p} / {total}"), "exp-rank"),
        None => (String::from("—"), "exp-rank"),
    }
}

fn render_group_table(scoreboard: &Scoreboard, model: &ipbr_core::ModelRecord) -> String {
    if model.groups.is_empty() {
        return r#"<div class="muted">no group scores</div>"#.to_string();
    }
    let mut html = String::from(r#"<div class="exp-table">"#);
    for (group, score) in &model.groups {
        let group_owned = group.clone();
        let rank = rank_for(scoreboard, &model.canonical_id, |m| {
            m.groups.get(&group_owned).copied()
        });
        let bar_width = rank_bar_width(rank);
        let (rank_label, rank_class) = rank_text(rank);
        html.push_str(&format!(
            r#"<span class="exp-label">{label}</span><span class="exp-bar"><span class="exp-bar-fill" style="width:{bar_width:.0}%"></span></span><span class="exp-value" data-tier="{tier}">{score:.1}</span><span class="{rank_class}">{rank_label}</span>"#,
            label = html_escape(group),
            tier = score_tier(*score),
        ));
    }
    html.push_str("</div>");
    html
}

fn render_role_evidence(model: &ipbr_core::ModelRecord) -> String {
    if model.evidence.roles.is_empty() {
        return r#"<div class="muted">evidence summary unavailable</div>"#.to_string();
    }
    let mut html = String::from(r#"<div class="evidence-table">"#);
    for (label, key) in [
        ("idea", "I_raw"),
        ("plan", "P_raw"),
        ("build", "B_raw"),
        ("review", "R"),
    ] {
        let Some(coverage) = model.evidence.roles.get(key) else {
            continue;
        };
        let status = if coverage.provisional {
            "provisional"
        } else {
            "ranked"
        };
        write!(
            html,
            r#"<span class="exp-label">{label}</span><span class="evidence-value">{direct:.0}% direct</span><span class="evidence-value">{effective:.0}% confidence</span><span class="evidence-value">{families} families</span><span class="status-badge {status}">{status}</span>"#,
            direct = coverage.direct * 100.0,
            effective = coverage.effective * 100.0,
            families = coverage.family_count,
        )
        .unwrap();
    }
    html.push_str("</div>");
    html
}

fn render_metric_table(scoreboard: &Scoreboard, model: &ipbr_core::ModelRecord) -> String {
    if model.metrics.is_empty() {
        return r#"<div class="muted">no metrics</div>"#.to_string();
    }
    let ranked_metrics = ranked_metric_keys(&scoreboard.coefficients);
    let mut html = String::from(r#"<div class="exp-table exp-metric-table">"#);
    for (key, value) in &model.metrics {
        let key_owned = key.clone();
        let rank = rank_for(scoreboard, &model.canonical_id, |m| {
            m.metrics.get(&key_owned).copied()
        });
        let bar_width = rank_bar_width(rank);
        let (rank_label, rank_class) = rank_text(rank);
        let raw = model
            .raw_metrics
            .get(key)
            .map(|raw| format_raw_metric(*raw))
            .unwrap_or_else(|| "derived".to_string());
        let (evidence_class, evidence_title) = metric_evidence(model, key);
        let evidence_title = sanitize_evidence_tooltip(&evidence_title);
        let use_class = if ranked_metrics.contains(key) {
            "rank input"
        } else {
            "reference"
        };
        html.push_str(&format!(
            r#"<span class="exp-label">{key}</span><span class="exp-raw">{raw}</span><span class="exp-bar"><span class="exp-bar-fill" style="width:{bar_width:.0}%"></span></span><span class="exp-value" data-tier="{tier}">{value:.1}</span><span class="evidence-kind" title="{evidence_title}">{evidence_class} · {use_class}</span><span class="{rank_class}">{rank_label}</span>"#,
            key = html_escape(key),
            raw = html_escape(&raw),
            tier = score_tier(*value),
            evidence_title = html_escape(&evidence_title),
        ));
    }
    html.push_str("</div>");
    html
}

fn metric_evidence(model: &ipbr_core::ModelRecord, metric: &str) -> (&'static str, String) {
    if model.raw_metrics.contains_key(metric) {
        let source = model
            .metric_sources
            .get(metric)
            .map(String::as_str)
            .unwrap_or("direct source");
        let detail = if model.curated_overrides.contains(metric) {
            "Curated direct observation; full citation is in scoreboard.toml".to_string()
        } else if let Some(note) = model.metric_citations.get(metric) {
            format!("Direct observation from {source}: {note}")
        } else {
            format!("Direct observation from {source}")
        };
        return ("direct", detail);
    }
    ("derived", "Composite of normalized inputs".to_string())
}

/// Evidence notes retain full upstream URLs in `scoreboard.toml`, but the
/// static HTML deliberately has no external-reference markers. Sanitize those
/// marker strings in tooltip text while preserving surrounding provenance.
fn sanitize_evidence_tooltip(input: &str) -> String {
    let mut remaining = input;
    let mut output = String::with_capacity(input.len());
    loop {
        let http = remaining.find("http://");
        let https = remaining.find("https://");
        let Some(start) = (match (http, https) {
            (Some(a), Some(b)) => Some(a.min(b)),
            (Some(a), None) | (None, Some(a)) => Some(a),
            (None, None) => None,
        }) else {
            output.push_str(remaining);
            break;
        };

        output.push_str(&remaining[..start]);
        output.push_str("[upstream URL in scoreboard.toml]");
        let url = &remaining[start..];
        let end = url
            .find(|c: char| c.is_whitespace() || matches!(c, ';' | ',' | ')' | ']'))
            .unwrap_or(url.len());
        remaining = &url[end..];
    }
    // `data:` is also rejected by the self-contained-site validator. It can
    // occur innocently inside prose such as `metadata:` even when no data URI
    // exists, so keep the wording while changing the delimiter.
    output.replace("data:", "data —")
}

fn format_raw_metric(value: f64) -> String {
    if value.abs() >= 1_000.0 {
        format!("{value:.1}")
    } else if value.abs() >= 100.0 {
        format!("{value:.2}")
    } else {
        format!("{value:.3}")
    }
}

fn ranked_metric_keys(
    coefficients: &ipbr_core::Coefficients,
) -> std::collections::BTreeSet<String> {
    fn expand(
        metric: &str,
        coefficients: &ipbr_core::Coefficients,
        keys: &mut std::collections::BTreeSet<String>,
        visiting: &mut std::collections::BTreeSet<String>,
    ) {
        keys.insert(metric.to_string());
        if coefficients.precedence_composites.contains(metric) {
            return;
        }
        let Some(inputs) = coefficients.composite_metrics.get(metric) else {
            return;
        };
        if !visiting.insert(metric.to_string()) {
            return;
        }
        for input in inputs.keys() {
            expand(input, coefficients, keys, visiting);
        }
        visiting.remove(metric);
    }

    let mut keys = std::collections::BTreeSet::new();
    for groups in coefficients.final_score_weights.values() {
        for group in groups.keys() {
            if let Some(metrics) = coefficients.group_weights.get(group) {
                for metric in metrics.keys() {
                    expand(
                        metric,
                        coefficients,
                        &mut keys,
                        &mut std::collections::BTreeSet::new(),
                    );
                }
            }
        }
    }
    keys
}

fn render_source_pills(scoreboard: &Scoreboard, model: &ipbr_core::ModelRecord) -> String {
    if model.sources.is_empty() {
        return r#"<div class="muted">no sources</div>"#.to_string();
    }
    let mut html = String::new();
    for source in &model.sources {
        let status = scoreboard
            .source_summary
            .get(source)
            .map(|s| s.status.as_str())
            .unwrap_or("unknown");
        html.push_str(&format!(
            r#"<span class="pill" title="{status}">{name}</span>"#,
            name = html_escape(source),
            status = html_escape(status),
        ));
    }
    html
}

fn render_missing_pills(model: &ipbr_core::ModelRecord) -> String {
    if model.missing.metrics.is_empty() {
        return r#"<span class="muted">none</span>"#.to_string();
    }
    let mut html = String::new();
    for metric in &model.missing.metrics {
        html.push_str(&format!(
            r#"<span class="pill">{m}</span>"#,
            m = html_escape(metric),
        ));
    }
    html
}

